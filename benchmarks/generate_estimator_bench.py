#!/usr/bin/env python3
"""Emit the Flow side of the wide estimator benchmark from the registry.

Writing 172 timing blocks by hand invites 172 small mistakes, so they are
generated from `estimator_coverage.json`. The output is split across several
files because Flow issue #469 miscompiles some functions once a program grows
past a certain size, and the benchmark is the wrong place to find that out.

Each block times a fit, times the companion predict or transform when one
exists, and prints one parseable line:

    ESTIMATOR|<flow name>|<fit ms>|<pred ms>|ok
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "benchmarks" / "estimator_coverage.json"
OUTDIR = ROOT / "benchmarks" / "generated"

import importlib.util

_spec = importlib.util.spec_from_file_location("estimator_coverage", ROOT / "benchmarks" / "estimator_coverage.py")
_cov = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_cov)

HEADER = '''# Generated by benchmarks/generate_estimator_bench.py. Do not edit.
#
# One timing block per Flow estimator that the registry marks runnable.
# Regenerate with:
#   python benchmarks/estimator_coverage.py
#   python benchmarks/generate_estimator_bench.py

import "lib/scikit/scikit.flow"

extern {
    function printf(fmt: string, ...) -> i32
    function flow_now_ns() -> i64
    function malloc(size: i64) -> ptr<void>
    function free(p: ptr<void>) -> void
    function fflush(stream: ptr<void>) -> i32
}

function ms_between(start: i64, finish: i64) -> f32 {
    return ((((finish - start) as f64) / 1000000.0) as f32)
}
'''


SUFFIX = {
    "classification": "c",
    "regression": "r",
    "unsupervised": "c",
    "multioutput": "r",
    "multioutput_class": "c",
}


def dataset_kind(entry: dict) -> str:
    names = [p["name"] for p in entry["fit"]["parameters"]]
    types = {p["name"]: p["type"] for p in entry["fit"]["parameters"]}
    if "y" not in names and "Y" not in names:
        return "unsupervised"
    if "Y" in names:
        # A multi-output classifier handed continuous targets is not doing the
        # work its scikit-learn counterpart would refuse to do at all.
        return "multioutput_class" if "classifier" in entry["flow_estimator"] or "chain" in entry["flow_estimator"] else "multioutput"
    if "n_classes" in names:
        return "classification"
    if types.get("y") == "ptr<i32>":
        return "classification"
    return "regression"


def fit_arguments(entry: dict, kind: str) -> tuple[list[str], list[str]]:
    """Returns (preamble lines, argument expressions)."""
    pre: list[str] = []
    args: list[str] = []
    suffix = SUFFIX[kind]
    for i, p in enumerate(entry["fit"]["parameters"]):
        name, ptype = p["name"], p["type"]
        if i == 0:
            args.append(f"X_{suffix}")
            continue
        if name == "y":
            args.append(f"y_{suffix}" if ptype == "ptr<f32>" else f"yi_{suffix}")
            continue
        if name == "Y":
            multi = "Y_labels" if kind == "multioutput_class" else "Y_multi"
            if ptype == "Matrix":
                args.append(multi)
                continue
            if ptype.replace(" ", "") == "ptr<ptr<f32>>":
                args.append("Y_label_rows" if kind == "multioutput_class" else "Y_rows")
                continue
        if name == "n_classes":
            args.append("3" if kind == "classification" else "1")
            continue
        if name == "n_samples":
            args.append(f"n_{suffix}")
            continue
        if name == "n_features":
            args.append(f"f_{suffix}")
            continue
        if name in _cov.PREAMBLE_ARGS:
            decl_type, literal = _cov.PREAMBLE_ARGS[name]
            local = f"{name}_{entry['flow_estimator']}"
            pre.append(f"    let {local}: {decl_type} = {literal}")
            args.append(local)
            continue
        typed = _cov.TYPED_ARGS.get((name, ptype))
        if typed is not None:
            args.append(typed)
            continue
        args.append(_cov.ARGS[name])
    return pre, args


# One value out of every result is added to a running sink, which main prints
# on a line the parser ignores. Without it, clang at -O3 is free to delete a
# transform whose result is freed without being read, and two rows came back at
# exactly 0.000000 ms because it did.
def sink_line(var: str, returns: str, indent: str = "        ") -> list[str]:
    if returns == "Matrix":
        return [
            f"{indent}if {var}.rows > 0 {{",
            f"{indent}    if {var}.cols > 0 {{ sink = sink + {var}.data[0] }}",
            f"{indent}}}",
        ]
    return [f"{indent}sink = sink + {var}[0]"]


def block(entry: dict) -> str:
    """One estimator: probe, choose a repeat count, then time fit and predict.

    A single shot does not measure an estimator that finishes in microseconds.
    StandardScaler on 150 rows by 4 came back as 0.001 ms, which is the clock's
    resolution rather than its cost, and spectral_biclustering produced a
    23600x ratio out of the same rounding. The probe below picks a repeat count
    so every estimator is timed over something the clock can see.
    """
    name = entry["flow_estimator"]
    kind = dataset_kind(entry)
    suffix = SUFFIX[kind]
    pre, args = fit_arguments(entry, kind)
    ret = entry["fit"]["returns"]
    call = f"{entry['fit']['name']}({', '.join(args)})"
    free = entry["companions"].get("free")
    free_ok = free is not None and len(free["parameters"]) == 1

    comp = entry["companions"].get("predict") or entry["companions"].get("transform")
    comp_ok = (
        comp is not None
        and len(comp["parameters"]) == 2
        and comp["parameters"][1]["type"] == "Matrix"
        and comp["returns"] in ("Matrix", "ptr<f32>")
    )

    def release(var: str, kind_: str) -> str:
        return "matrix_free(%s)" % var if kind_ == "Matrix" else "array_free_f32(%s)" % var

    lines = [f"    # ---- {name} ({kind}) ----"]
    lines += pre
    # Probe once to size the repeat count, then release it.
    lines.append("    t0 = flow_now_ns()")
    lines.append(f"    let probe_{name}: {ret} = {call}")
    lines.append("    t1 = flow_now_ns()")
    if free_ok:
        lines.append(f"    {free['name']}(probe_{name})")
    lines.append("    reps = 1")
    lines.append("    if (t1 - t0) < 200000 { reps = 200 }")
    lines.append("    elif (t1 - t0) < 2000000 { reps = 20 }")
    lines.append("    elif (t1 - t0) < 20000000 { reps = 5 }")

    # Timed fit loop.
    lines.append("    t0 = flow_now_ns()")
    lines.append("    for rep in 0 to reps {")
    lines.append(f"        let m_{name}: {ret} = {call}")
    if free_ok:
        lines.append(f"        {free['name']}(m_{name})")
    lines.append("    }")
    lines.append("    t1 = flow_now_ns()")

    # Timed predict loop against one fitted model.
    if comp_ok:
        lines.append(f"    let fitted_{name}: {ret} = {call}")
        lines.append("    t2 = flow_now_ns()")
        lines.append("    for rep2 in 0 to reps {")
        lines.append(f"        let o_{name}: {comp['returns']} = {comp['name']}(fitted_{name}, X_{suffix})")
        lines += sink_line(f"o_{name}", comp["returns"])
        lines.append("        " + release(f"o_{name}", comp["returns"]))
        lines.append("    }")
        lines.append("    t3 = flow_now_ns()")
        if free_ok:
            lines.append(f"    {free['name']}(fitted_{name})")
        pred_expr = "ms_between(t2, t3) / (reps as f32)"
    else:
        pred_expr = "0.0"

    lines.append(
        f'    printf("ESTIMATOR|{name}|%.9f|%.9f|%d|ok\\n", '
        f"ms_between(t0, t1) / (reps as f32), {pred_expr}, reps)"
    )
    # Without this, one estimator trapping takes the whole file's buffered
    # output with it and the run looks empty rather than partial.
    lines.append("    fflush(null)")
    return "\n".join(lines) + "\n"


def shaped_block(entry: dict) -> str:
    """One estimator whose fit does not begin with a feature matrix.

    The registry carries the call for these, because the generic path above
    builds one shape of call and these take a target vector, a feature count or
    a pair of scalars instead. Everything else about the timing is the same, so
    a shaped row is ranked like any other.
    """
    name = entry["flow_estimator"]
    shape = entry["shape"]
    kind = shape["dataset"]
    ret = entry["fit"]["returns"]
    call = f"{entry['fit']['name']}({', '.join(shape['flow_fit'])})"
    free = entry["companions"].get("free")
    # A fit that takes a composed object built outside the timing mutates that
    # object and hands it back, so freeing the result on every repeat would free
    # what the next repeat is about to read. Those rows free once, after the
    # timing, and leak the state a repeat leaves behind, which is a few hundred
    # bytes per pass over a four-column design.
    free_in_loop = shape.get("flow_free", "loop") == "loop"
    free_ok = free is not None and len(free["parameters"]) == 1
    comp = entry["companions"].get("transform") or entry["companions"].get("predict")
    work = shape.get("flow_work")
    # A recipe can name the work function itself, for an estimator whose
    # companion is called something other than predict or transform.
    if shape.get("flow_work_fn"):
        comp = {"name": shape["flow_work_fn"], "returns": shape["flow_work_returns"]}
    comp_ok = comp is not None and work is not None and (
        comp["returns"] in ("Matrix", "ptr<f32>") or shape.get("flow_work_release")
    )

    lines = [f"    # ---- {name} ({kind}, written out) ----"]
    if shape.get("corpus"):
        docs = shape["corpus"]
        lines.append(f"    let {name}_docs: array<string, {len(docs)}> = [")
        for i, doc in enumerate(docs):
            tail = "," if i + 1 < len(docs) else ""
            lines.append(f'        "{doc}"{tail}')
        lines.append("    ]")
    for pre_line in shape.get("flow_preamble", []):
        lines.append("    " + pre_line)
    lines.append("    t0 = flow_now_ns()")
    lines.append(f"    let probe_{name}: {ret} = {call}")
    lines.append("    t1 = flow_now_ns()")
    if free_ok and free_in_loop:
        lines.append(f"    {free['name']}(probe_{name})")
    lines.append("    reps = 1")
    lines.append("    if (t1 - t0) < 200000 { reps = 200 }")
    lines.append("    elif (t1 - t0) < 2000000 { reps = 20 }")
    lines.append("    elif (t1 - t0) < 20000000 { reps = 5 }")
    lines.append("    t0 = flow_now_ns()")
    lines.append("    for rep in 0 to reps {")
    lines.append(f"        let m_{name}: {ret} = {call}")
    if free_ok and free_in_loop:
        lines.append(f"        {free['name']}(m_{name})")
    lines.append("    }")
    lines.append("    t1 = flow_now_ns()")

    if comp_ok:
        release = "matrix_free" if comp["returns"] == "Matrix" else "array_free_f32"
        lines.append(f"    let fitted_{name}: {ret} = {call}")
        lines.append("    t2 = flow_now_ns()")
        lines.append("    for rep2 in 0 to reps {")
        lines.append(f"        let o_{name}: {comp['returns']} = "
                     f"{comp['name']}(fitted_{name}, {', '.join(work)})")
        if comp["returns"] in ("Matrix", "ptr<f32>"):
            lines += sink_line(f"o_{name}", comp["returns"])
        if shape.get("flow_work_release"):
            lines.append("        " + shape["flow_work_release"].format(var=f"o_{name}"))
        else:
            lines.append(f"        {release}(o_{name})")
        lines.append("    }")
        lines.append("    t3 = flow_now_ns()")
        if free_ok:
            lines.append(f"    {free['name']}(fitted_{name})")
        pred_expr = "ms_between(t2, t3) / (reps as f32)"
    else:
        pred_expr = "0.0"
        if free_ok and not free_in_loop:
            lines.append(f"    {free['name']}(probe_{name})")

    lines.append(
        f'    printf("ESTIMATOR|{name}|%.9f|%.9f|%d|ok\\n", '
        f"ms_between(t0, t1) / (reps as f32), {pred_expr}, reps)"
    )
    lines.append("    fflush(null)")
    return "\n".join(lines) + "\n"


def chunk_file(index: int, entries: list[dict]) -> str:
    body = "\n".join(shaped_block(e) if e["bucket"] == "shaped" else block(e) for e in entries)
    return f'''{HEADER}
function main() -> i32 {{
    let iris: Dataset = load_iris()
    let diabetes: Dataset = load_diabetes()
    let X_c: Matrix = iris.X
    let y_c: ptr<f32> = iris.y
    let n_c: i32 = X_c.rows
    let f_c: i32 = X_c.cols
    let X_r: Matrix = diabetes.X
    let y_r: ptr<f32> = diabetes.y
    let n_r: i32 = X_r.rows
    let f_r: i32 = X_r.cols

    let yi_c: ptr<i32> = malloc((n_c as i64) * 4) as ptr<i32>
    for i in 0 to n_c {{ yi_c[i] = y_c[i] as i32 }}
    let yi_r: ptr<i32> = malloc((n_r as i64) * 4) as ptr<i32>
    for i in 0 to n_r {{ yi_r[i] = y_r[i] as i32 }}

    # A two-column target for the cross-decomposition estimators.
    let Y_multi: Matrix = matrix_new(n_r, 2)
    for i in 0 to n_r {{
        matrix_set(Y_multi, i, 0, y_r[i])
        matrix_set(Y_multi, i, 1, y_r[i] * 0.5)
    }}

    # Label-valued targets for the multi-output classifiers.
    let Y_labels: Matrix = matrix_new(n_c, 2)
    let Y_label_rows: ptr<ptr<f32> > = malloc((n_c as i64) * 8) as ptr<ptr<f32> >
    for i in 0 to n_c {{
        let a: f32 = y_c[i]
        let b: f32 = ((((y_c[i] as i32) + 1) % 3) as f32)
        matrix_set(Y_labels, i, 0, a)
        matrix_set(Y_labels, i, 1, b)
        let lrow: ptr<f32> = array_new_f32(2)
        lrow[0] = a
        lrow[1] = b
        Y_label_rows[i] = lrow
    }}

    let Y_rows: ptr<ptr<f32> > = malloc((n_r as i64) * 8) as ptr<ptr<f32> >
    for i in 0 to n_r {{
        let row: ptr<f32> = array_new_f32(2)
        row[0] = y_r[i]
        row[1] = y_r[i] * 0.5
        Y_rows[i] = row
    }}

    # A one-dimensional x for the isotonic row, which regresses against a
    # single ordered variable rather than a design.
    let x1d_r: ptr<f32> = array_new_f32(n_r)
    for i in 0 to n_r {{ x1d_r[i] = matrix_at(X_r, i, 0) }}

    # Per-feature importances for the selector row, which takes the weights a
    # fitted model would hand it rather than a design.
    let w_f: ptr<f32> = array_new_f32(f_c)
    for i in 0 to f_c {{ w_f[i] = 1.0 / ((i + 1) as f32) }}

    let mut t0: i64 = 0
    let mut t1: i64 = 0
    let mut t2: i64 = 0
    let mut t3: i64 = 0
    let mut reps: i32 = 1
    let mut sink: f32 = 0.0

{body}
    for i in 0 to n_c {{ array_free_f32(Y_label_rows[i]) }}
    free(Y_label_rows as ptr<void>)
    matrix_free(Y_labels)
    for i in 0 to n_r {{ array_free_f32(Y_rows[i]) }}
    free(Y_rows as ptr<void>)
    matrix_free(Y_multi)
    free(yi_c as ptr<void>)
    free(yi_r as ptr<void>)
    array_free_f32(x1d_r)
    array_free_f32(w_f)
    # The sink is printed so the work above cannot be optimized away. The
    # parser matches ESTIMATOR lines only, so this one is ignored.
    printf("SINK|%.9f\\n", sink)
    return 0
}}
'''


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--per-file", type=int, default=20)
    ap.add_argument("--outdir", type=Path, default=OUTDIR)
    ap.add_argument("--only", help="comma separated estimator names, for bisecting a compile "
                                   "failure or re-timing one group")
    ap.add_argument("--prefix", default="bench_estimators",
                    help="output file prefix, so a subset written elsewhere cannot collide with "
                         "the committed files or with another process in the shared build directory")
    args = ap.parse_args()

    registry = json.loads(REGISTRY.read_text())
    # Simplified implementations are timed too, because compare_estimators.py
    # shows their times while withholding a ratio. Leaving them out of the
    # race would make the page quietly drop four rows.
    timed = ("runnable", "shaped", "simplified")
    runnable = [e for e in registry["entries"] if e["bucket"] in timed]
    if args.only:
        wanted = [n.strip() for n in args.only.split(",") if n.strip()]
        runnable = [e for e in runnable if e["flow_estimator"] in wanted]
        found = {e["flow_estimator"] for e in runnable}
        missing = [n for n in wanted if n not in found]
        if missing:
            raise SystemExit(f"not timed registry entries: {', '.join(missing)}")

    args.outdir.mkdir(parents=True, exist_ok=True)
    for stale in args.outdir.glob(f"{args.prefix}_*.flow"):
        stale.unlink()

    written = []
    for i in range(0, len(runnable), args.per_file):
        part = runnable[i : i + args.per_file]
        path = args.outdir / f"{args.prefix}_{i // args.per_file:02d}.flow"
        path.write_text(chunk_file(i // args.per_file, part))
        written.append((path.name, len(part)))

    for name, n in written:
        print(f"{name}: {n} estimators")
    print(f"total {len(runnable)} estimators across {len(written)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
